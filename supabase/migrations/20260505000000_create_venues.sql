-- Base venue catalog for FOGEAT.
-- After this migration the app reads editable venue data from public.venues.

create table if not exists public.venues (
  id integer primary key,
  name text not null,
  category text not null,
  subcategory text not null default '',
  address text not null,
  icon text not null default '📍',
  rating numeric(2,1) not null default 0,
  review_count integer not null default 0,
  instagram text,
  lat double precision not null,
  lng double precision not null,
  dishes jsonb,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.venues enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
  );
$$;

grant execute on function public.is_admin() to authenticated;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists venues_set_updated_at on public.venues;
create trigger venues_set_updated_at
before update on public.venues
for each row execute function public.set_updated_at();

drop policy if exists "venues are readable by everyone" on public.venues;
create policy "venues are readable by everyone"
on public.venues for select
using (true);

drop policy if exists "admins can insert venues" on public.venues;
create policy "admins can insert venues"
on public.venues for insert
to authenticated
with check (public.is_admin());

drop policy if exists "admins can update venues" on public.venues;
create policy "admins can update venues"
on public.venues for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "admins can delete venues" on public.venues;
create policy "admins can delete venues"
on public.venues for delete
to authenticated
using (public.is_admin());

grant select on table public.venues to anon, authenticated;
grant insert, update, delete on table public.venues to authenticated;

